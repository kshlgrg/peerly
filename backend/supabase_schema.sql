-- Create chat_logs table for storing chat packets with user behavior tracking
CREATE TABLE IF NOT EXISTS chat_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id VARCHAR(255) NOT NULL,
    client_id VARCHAR(255) NOT NULL,
    client_ip VARCHAR(45),  -- Supports both IPv4 and IPv6
    user_type VARCHAR(20) NOT NULL, -- 'user1' or 'user2' in the chat
    message_type VARCHAR(50) NOT NULL, -- 'message', 'next', 'report', 'game', etc.
    message_content TEXT,
    metadata JSONB, -- Additional data like game state, timestamps, etc.
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    matched_at TIMESTAMP WITH TIME ZONE, -- When users were matched
    room_mode VARCHAR(20) NOT NULL -- 'text' or 'video'
);

-- Create indexes for performance
CREATE INDEX IF NOT EXISTS idx_chat_logs_session_id ON chat_logs(session_id);
CREATE INDEX IF NOT EXISTS idx_chat_logs_client_id ON chat_logs(client_id);
CREATE INDEX IF NOT EXISTS idx_chat_logs_created_at ON chat_logs(created_at);
CREATE INDEX IF NOT EXISTS idx_chat_logs_room_mode ON chat_logs(room_mode);

-- Create session summary table for analytics
CREATE TABLE IF NOT EXISTS chat_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id VARCHAR(255) UNIQUE NOT NULL,
    client1_id VARCHAR(255) NOT NULL,
    client1_ip VARCHAR(45),
    client2_id VARCHAR(255),
    client2_ip VARCHAR(45),
    room_mode VARCHAR(20) NOT NULL,
    started_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    ended_at TIMESTAMP WITH TIME ZONE,
    message_count INTEGER DEFAULT 0,
    next_count INTEGER DEFAULT 0,
    report_count INTEGER DEFAULT 0,
    game_count INTEGER DEFAULT 0,
    session_duration_seconds INTEGER,
    end_reason VARCHAR(50) -- 'disconnect', 'next', 'manual_end'
);

-- Create indexes for session analytics
CREATE INDEX IF NOT EXISTS idx_chat_sessions_session_id ON chat_sessions(session_id);
CREATE INDEX IF NOT EXISTS idx_chat_sessions_started_at ON chat_sessions(started_at);
CREATE INDEX IF NOT EXISTS idx_chat_sessions_room_mode ON chat_sessions(room_mode);

-- Enable Row Level Security (RLS) for security
ALTER TABLE chat_logs ENABLE ROW LEVEL SECURITY;
ALTER TABLE chat_sessions ENABLE ROW LEVEL SECURITY;

-- Create policy for chat_logs (restrictive - only service role can access)
CREATE POLICY "Service role only access" ON chat_logs
    FOR ALL USING (auth.jwt() ->> 'role' = 'service_role');

-- Create policy for chat_sessions (restrictive - only service role can access)
CREATE POLICY "Service role only access" ON chat_sessions
    FOR ALL USING (auth.jwt() ->> 'role' = 'service_role');

-- Create function to update session statistics
CREATE OR REPLACE FUNCTION update_session_stats()
RETURNS TRIGGER AS $$
BEGIN
    -- Update message count for new chat messages
    IF NEW.message_type = 'message' THEN
        UPDATE chat_sessions
        SET message_count = message_count + 1
        WHERE session_id = NEW.session_id;
    -- Update next count for skip actions
    ELSIF NEW.message_type = 'next' THEN
        UPDATE chat_sessions
        SET next_count = next_count + 1
        WHERE session_id = NEW.session_id;
    -- Update report count for reports
    ELSIF NEW.message_type = 'report' THEN
        UPDATE chat_sessions
        SET report_count = report_count + 1
        WHERE session_id = NEW.session_id;
    -- Update game count for game actions
    ELSIF NEW.message_type = 'game' THEN
        UPDATE chat_sessions
        SET game_count = game_count + 1
        WHERE session_id = NEW.session_id;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Create trigger to automatically update session statistics
CREATE TRIGGER trigger_update_session_stats
    AFTER INSERT ON chat_logs
    FOR EACH ROW
    EXECUTE FUNCTION update_session_stats();

-- Create view for chat analytics
CREATE OR REPLACE VIEW chat_analytics AS
SELECT
    DATE_TRUNC('hour', cs.started_at) as hour_bucket,
    cs.room_mode,
    COUNT(*) as session_count,
    AVG(cs.session_duration_seconds) as avg_duration_seconds,
    AVG(cs.message_count) as avg_messages_per_session,
    SUM(cs.message_count) as total_messages,
    SUM(cs.next_count) as total_skips,
    SUM(cs.report_count) as total_reports,
    SUM(cs.game_count) as total_games
FROM chat_sessions cs
WHERE cs.started_at >= NOW() - INTERVAL '30 days'
GROUP BY DATE_TRUNC('hour', cs.started_at), cs.room_mode
ORDER BY hour_bucket DESC;

-- Grant access to analytics view
CREATE POLICY "Service role analytics access" ON chat_analytics
    FOR SELECT USING (auth.jwt() ->> 'role' = 'service_role');